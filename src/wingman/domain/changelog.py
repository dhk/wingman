"""Wingman's own changelog: curated, merged-PR titles (RFC-038, issue #145).

Source of truth is `src/wingman/changelog_data.py`, a committed static
module regenerated by `scripts/generate_changelog.py` at release time — NOT
a live `git log` read. The running process (installed via `uv tool install`,
per docs/INSTALL.md) has no `.git` directory to read: `uv tool install`
builds a wheel into an isolated tool venv even for the "install from a local
checkout" path, verified empirically against a real installed instance
(nothing under the tool's site-packages carries VCS history). A generated
file that ships as ordinary package source is the only option that works
across every documented install path (git URL, local checkout, PyPI-style
wheel). See RFC-038 for the full trade-off.

Titles render verbatim — no model rewrite (issue #145 scope). The
user-facing filter below is a deliberately loose, deterministic heuristic:
only titles that unambiguously read as internal repo/process bookkeeping
are excluded, per the issue's own "when in doubt, include" instruction.

#202: the static file went 61 PRs stale with no signal — `changelog`
reported a confident "0 new" instead of an unverified one. Since there is
still no live git access at runtime (RFC-038's constraint didn't change),
the fix is a same-shape defense: the generator stamps what it ran at, and
`render_changelog` leads with a plain warning rather than silently
rendering counts from data it can't vouch for.

What it stamps is a DISTANCE (`changelog_data.GENERATED_FROM_DISTANCE`,
commits past the last tag) as well as the commit sha. The sha is an
identity — it is what the self-consistency test regenerates against — but
it cannot answer freshness, because generating this file and committing it
produces a different sha by construction. A stamped sha therefore never
equals the sha of any build containing it, so comparing them warned after
every correct regeneration, and a warning that fires when nothing is wrong
is how a real one gets ignored (#228 review). Distance survives being
committed, and is the same number a version's `.devN` carries, so the two
subtract into "how many merges are missing".

`wingman-ctl upgrade`/`cycle` regenerate the file as part of every upgrade,
so drift should stay at most one commit in practice; the CI ceiling in
tests/unit/test_changelog_freshness.py stops it reaching main at all, and
this runtime check is what an installed build can still say for itself.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date as date_cls
from datetime import timedelta


@dataclass(frozen=True)
class ChangelogEntry:
    date: str  # ISO "YYYY-MM-DD" — the merge commit's date, our PR-merge-date proxy
    pr: int
    title: str


# Shared by the web UI tab and the MCP tool so both surfaces show the same
# horizon — long enough to cover "what's happened lately", short enough that
# neither surface has to render this repo's entire history.
DEFAULT_DISPLAY_LIMIT = 60

#: Where a merged PR can be read. An entry carries a bare number, which is
#: only meaningful to somebody who already knows the repository — so every
#: surface that shows one renders it as a link people can follow (#357).
#: The repository being private is not a reason to withhold the URL: a
#: reader without access gets a sign-in page, which at least tells them
#: what they are missing, where a bare "#123" tells them nothing at all.
PR_URL_BASE = "https://github.com/dhk/wingman/pull/"


def pr_url(pr: int) -> str:
    """The URL for one merged PR."""
    return f"{PR_URL_BASE}{pr}"


# Deliberately small and specific: each pattern targets a category the repo's
# own history actually produces (see scripts/generate_changelog.py's sample),
# not a broad guess at what "internal" might mean. A missed internal title
# just shows up in the list; a wrongly-excluded user-facing one hides a real
# change — the issue's stated preference is to err toward the former.
_INTERNAL_TITLE_PATTERNS = (
    re.compile(r"\bsession (snapshot|context)\b", re.IGNORECASE),  # repo-continuity notes
    re.compile(r"^address review:", re.IGNORECASE),  # code-review-remediation follow-ups
    re.compile(r"^(chore|test|tests|ci|internal)\s*:", re.IGNORECASE),
    re.compile(r"\btest[- ]only\b", re.IGNORECASE),
    re.compile(r"\badmin\b.{0,40}\bfix", re.IGNORECASE),  # admin-page-only bugfixes
)


def is_user_facing(title: str) -> bool:
    """True unless the title unambiguously reads as internal-only."""
    return not any(pattern.search(title) for pattern in _INTERNAL_TITLE_PATTERNS)


def load_entries() -> list[ChangelogEntry]:
    """Every generated entry, in the data file's own order."""
    from wingman.changelog_data import CHANGELOG_DATA

    return [ChangelogEntry(date=date, pr=pr, title=title) for date, pr, title in CHANGELOG_DATA]


def user_facing_entries() -> list[ChangelogEntry]:
    """Curated entries, newest first."""
    entries = [entry for entry in load_entries() if is_user_facing(entry.title)]
    return sorted(entries, key=lambda entry: entry.date, reverse=True)


def internal_only_entries() -> list[ChangelogEntry]:
    """Entries the curation filter rejected — the other half of user_facing_entries,
    surfaced so a real zero can be told apart from a filtered one (#202)."""
    entries = [entry for entry in load_entries() if not is_user_facing(entry.title)]
    return sorted(entries, key=lambda entry: entry.date, reverse=True)


_DEV_DISTANCE_RE = re.compile(r"\.dev(\d+)")

# Regenerating writes changelog_data.py; committing it makes a new commit.
# So the build that CONTAINS a given regeneration is always at least one
# commit past the one it was generated at, and a stricter allowance would
# warn every single time the file is correctly regenerated and committed.
#
# This is the runtime half of a pair. The other half is the ceiling in
# tests/unit/test_changelog_freshness.py, which fails CI once the committed
# data falls too far behind HEAD. That test is the primary defence — it
# stops drift from reaching main at all. This note is what an installed
# build can still say for itself, having no git to consult. They disagreed
# once (the test called a one-commit lag harmless while this warned about
# it), which is what surfaced the bug fixed here; keep them in view of
# each other.
_LAG_ALLOWANCE = 1


def _distance_past_tag(version_string: str) -> int | None:
    """Commits past the last tag, from a version's '.devN', or None.

    None on an exact-tag build (no '.devN' at all) and on anything
    unparseable — both mean "can't verify", not "stale", so callers must
    treat None as silence.
    """
    match = _DEV_DISTANCE_RE.search(version_string)
    return int(match.group(1)) if match else None


def staleness_note(version_string: str) -> str | None:
    """None when the changelog data is current (or can't be checked); a
    warning naming HOW MANY merges are missing when it is behind (#202).

    Freshness is measured in distance, not commit identity. Comparing
    GENERATED_FROM_COMMIT against the running build's commit could never
    return "fresh" for a committed artifact: generating the file and
    committing it produces a different sha by construction, so that check
    warned after every correct regeneration — and a warning that fires when
    nothing is wrong is how a real one gets ignored. The sha is still
    stamped, and is still what the self-consistency test regenerates
    against; it is simply the wrong question to ask about freshness.

    A version's '.devN' is the same count the generator stamps, so
    subtracting them gives the number of merges this list cannot vouch
    for. If a new tag landed since generation the running count restarts
    lower, the subtraction goes negative, and this stays silent — the safe
    direction when the two numbers aren't comparable.
    """
    from wingman.changelog_data import GENERATED_FROM_DISTANCE

    if GENERATED_FROM_DISTANCE < 0:
        return None
    running = _distance_past_tag(version_string)
    if running is None:
        return None
    behind = running - GENERATED_FROM_DISTANCE - _LAG_ALLOWANCE
    if behind <= 0:
        return None
    merges = "merge" if behind == 1 else "merges"
    return (
        f"Note: this list is {behind} {merges} behind the running build, so recent "
        "entries are missing and any count below is a floor, not a total. "
        "Regenerate with 'python scripts/generate_changelog.py' (or "
        "'wingman-ctl upgrade', which does it automatically)."
    )


def counts_today_and_week(entries: list[ChangelogEntry], today: date_cls) -> tuple[int, int]:
    """(# dated today, # dated within the trailing 7-day window including today)."""
    window_start = today - timedelta(days=6)
    today_iso = today.isoformat()
    window_start_iso = window_start.isoformat()
    today_count = sum(1 for entry in entries if entry.date == today_iso)
    week_count = sum(1 for entry in entries if window_start_iso <= entry.date <= today_iso)
    return today_count, week_count


def render_changelog(today: date_cls, version_string: str | None = None) -> str:
    """Plain-text rendering shared by the MCP tool and the CLI: today/week
    counts up front, then curated entries newest first, capped at
    DEFAULT_DISPLAY_LIMIT.

    Never a confident zero (#202): a staleness note leads when the running
    build is known to be ahead of this data, and the header names how many
    entries the curation filter rejected in the same window, so a quiet
    week and a filtered one don't look identical. version_string defaults
    to the real running build; a caller only ever overrides it in tests.
    """
    if version_string is None:
        from wingman.version import wingman_version

        version_string = wingman_version()
    note = staleness_note(version_string)
    entries = user_facing_entries()
    internal = internal_only_entries()
    if not entries and not internal:
        body = "No changelog entries."
        return f"{note}\n\n{body}" if note else body
    today_count, week_count = counts_today_and_week(entries, today)
    _, internal_week_count = counts_today_and_week(internal, today)
    header = f"Changelog — {today_count} new today, {week_count} in the last 7 days."
    if internal_week_count:
        header += f" ({internal_week_count} internal-only filtered from the last 7 days)."
    lines = [note, ""] if note else []
    lines.extend([header, ""])
    lines.extend(
        f"- {entry.date} {entry.title} ({pr_url(entry.pr)})"
        for entry in entries[:DEFAULT_DISPLAY_LIMIT]
    )
    if len(entries) > DEFAULT_DISPLAY_LIMIT:
        lines.append("- …older entries omitted")
    return "\n".join(lines)
